export function goldPrep(coupleId) {
  const p = ACE_BOOK[coupleId];
  if (!p) throw new Error(`ace-book에 '${coupleId}' 커플의 gold prep이 없다. tests/ace-book.mjs에 먼저 써라.`);
  return { styling: p.styling, coaching: p.coaching, speech: p.speech };
}
